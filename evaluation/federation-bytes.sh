#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# F4 / R5 (bonus): how much bandwidth does federating ONLY aggregates save? Measured without the lab:
#   bash evaluation/federation-bytes.sh            # → evaluation/federation-bytes.md (table + method)
#
# A REAL Prometheus 2.53.5 (build/tools) with the REAL site rules (monitoring/site/rules) scrapes N
# "elements" (N = 10, 25, 50). Each element is a distinct label set (the inventory one: region, site,
# host, instance_name, role…) over two REAL exporters on 127.0.0.1: a node_exporter (Docker, read-only,
# no outbound network) and the project's Flask service (services/app.py). Then, per global request, it compares:
#   · /federate with the match[] of monitoring/global/prometheus.yml (what the project sends between sites)
#   · /federate with {__name__=~".+"}                               (what a central Prometheus WITHOUT hierarchy
#                                                                    would have to pull: every series)
# in series, text bytes and gzip bytes (Prometheus compresses if the client accepts it).
# Honest limit: all "elements" of one N share the same two exporters (same values); the number of series
# and the bytes per series are real, the variety of values is not.
# The global federates every 30 s (monitoring/global/prometheus.yml): 2 requests/min per site.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
export LC_ALL=C
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROMBIN="$ROOT/build/tools/prometheus-2"
[ -x "$PROMBIN" ] || bash "$ROOT/tools/fetch-tools.sh"
NE_IMAGE="${NE_IMAGE:-prom/node-exporter:v1.8.2}"
NE=127.0.0.1:19100; SVC=127.0.0.1:18000; PROM=127.0.0.1:19190
T="$(mktemp -d)"; OUT="$ROOT/evaluation/federation-bytes.md"
cleanup() { [ -n "${PP:-}" ] && kill "$PP" 2>/dev/null; [ -n "${SP:-}" ] && kill "$SP" 2>/dev/null
            docker rm -f ssle-f4-ne >/dev/null 2>&1 || true; rm -rf "$T"; }
trap cleanup EXIT

echo "[f4] real exporters: node_exporter ($NE_IMAGE) and the project's Flask service"
docker rm -f ssle-f4-ne >/dev/null 2>&1 || true
docker run -d --name ssle-f4-ne -p "$NE:9100" --read-only "$NE_IMAGE" >/dev/null
SSLE_ROLE=ingestion BIND=127.0.0.1 PORT=18000 uv run -q --with flask python3 "$ROOT/services/app.py" >"$T/svc.log" 2>&1 & SP=$!
for _ in $(seq 1 60); do curl -sf "http://$NE/metrics" >/dev/null && curl -sf "http://$SVC/metrics" >/dev/null && break; sleep 1; done
for _ in $(seq 1 30); do curl -s -o /dev/null "http://$SVC/work"; done      # some traffic for the histograms

measure() {  # measure <match[]=…>… → "series text_bytes gzip_bytes"
  local args=() m body
  for m in "$@"; do args+=(--data-urlencode "$m"); done
  body="$(curl -s -G "http://$PROM/federate" "${args[@]}")"
  local series; series=$(grep -vc '^#' <<<"$body" || true)
  local raw; raw=$(printf '%s' "$body" | wc -c)
  local gz; gz=$(printf '%s' "$body" | gzip -c | wc -c)
  echo "$series $raw $gz"
}
# the match[] of monitoring/global/prometheus.yml (what the project federates) and "everything" (no hierarchy)
AGG=('match[]={__name__=~"site.*:.*"}' 'match[]=up' 'match[]=ALERTS{alertstate="firing"}')
ALL=('match[]={__name__=~".+"}')

{
  echo "# F4 — Federation bandwidth: aggregates only vs all series"
  echo
  echo "> Generated by \`bash evaluation/federation-bytes.sh\` on $(date -u +%Y-%m-%dT%H:%MZ). Prometheus $("$PROMBIN" --version 2>&1 | head -1 | awk '{print $3}'),"
  echo "> real site rules, real exporters (node_exporter + Flask service), N elements per site. Method and limits"
  echo "> in the script header. The global federates every 30 s (\`monitoring/global/prometheus.yml\`) = 2 requests/min per site."
  echo
  echo "| N elements | series (aggregates) | series (all) | bytes/request aggregates (text · gzip) | bytes/request all (text · gzip) | savings (gzip) | kB/min per site, aggregates (gzip) |"
  echo "|---|---|---|---|---|---|---|"
} > "$T/table.md"

for N in 10 25 50; do
  { echo "global: {scrape_interval: 5s, evaluation_interval: 5s}"
    echo "rule_files: ['$ROOT/monitoring/site/rules/*.yml']"
    echo "scrape_configs:"
    for job in node services; do
      echo "- job_name: $job"
      echo "  static_configs:"
      for i in $(seq -w 1 "$N"); do
        tgt=$NE; [ "$job" = services ] && tgt=$SVC
        echo "  - targets: ['$tgt']"
        echo "    labels: {region: pt, site: opo, host: t490, instance_name: e$i, role: sensor, team: ops-opo, project: site-opo$( [ "$job" = services ] && echo ', service: sensor')}"
      done
    done
  } > "$T/prom-$N.yml"
  rm -rf "$T/data"
  "$PROMBIN" --config.file="$T/prom-$N.yml" --storage.tsdb.path="$T/data" --web.listen-address="$PROM" \
    --log.level=warn >"$T/prom-$N.log" 2>&1 & PP=$!
  for _ in $(seq 1 30); do curl -sf "http://$PROM/-/ready" >/dev/null && break; sleep 1; done
  sleep 25   # ≥ 4 scrapes + evaluations: the recording rules' rate()[5m] already have 2 samples
  read -r sa ra ga <<<"$(measure "${AGG[@]}")"
  read -r st rt gt <<<"$(measure "${ALL[@]}")"
  kill "$PP"; wait "$PP" 2>/dev/null || true; PP=""
  printf '| %s | %s | %s | %s · %s | %s · %s | %s %% | %.1f |\n' "$N" "$sa" "$st" "$ra" "$ga" "$rt" "$gt" \
    "$(awk -v a="$ga" -v b="$gt" 'BEGIN{printf "%.1f", 100*(1-a/b)}')" "$(awk -v g="$ga" 'BEGIN{print g*2/1000}')" >> "$T/table.md"
  echo "[f4] N=$N: aggregates $sa series / ${ga} B gzip · all $st series / ${gt} B gzip"
done
cat >> "$T/table.md" <<'EOF'

**Reading.** The federated series are `2N + 5`: the **5** site aggregates (`site:*`, constant with N) plus the
`up` of each target (2 per element: node + service), kept on purpose because the global root-cause analysis
needs to know **which** element is down. Without hierarchy, the central would pull ~820 series per element
(the entire node_exporter + service histograms). Savings stay above 99% at all N and
**increase** with N, because the aggregate side grows 2 series per element while the "all" side grows ~820.
EOF
cp "$T/table.md" "$OUT"
echo; cat "$OUT"
